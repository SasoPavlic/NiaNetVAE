#!/usr/bin/env python3
"""Render a completed study's artifacts as the wiki results page.

The results page is generated, never hand-written. Every number is read from
the study root that ``validate-study`` accepted, so documentation cannot drift
from evidence the way hand-maintained tables did.

Usage::

    python docs/build_results.py artifacts/metropt_controlled_v5 -o docs/wiki/07-results.md

Standard library only, so it runs without the nianetvae package installed.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

WORKFLOW_ORDER = (
    "iforest_static",
    "iforest_per_maintenance",
    "sae_static",
    "vae_static",
    "nianetvae_per_maintenance",
)


def read_json(path: Path) -> dict[str, Any] | None:
    if not path.is_file():
        return None
    return json.loads(path.read_text(encoding="utf-8"))


def fmt(value: Any, digits: int = 4) -> str:
    if value is None:
        return "-"
    if isinstance(value, bool):
        return "yes" if value else "no"
    if isinstance(value, float):
        return f"{value:.{digits}f}"
    return str(value)


def short(value: Any, size: int = 16) -> str:
    text = str(value)
    return f"`{text[:size]}...`" if len(text) > size else f"`{text}`"


def table(headers: list[str], rows: list[list[str]], numeric_from: int = 1) -> list[str]:
    separators = [
        "---:" if index >= numeric_from else "---" for index in range(len(headers))
    ]
    out = ["| " + " | ".join(headers) + " |", "|" + "|".join(separators) + "|"]
    out.extend("| " + " | ".join(row) + " |" for row in rows)
    out.append("")
    return out


def best(values: dict[str, Any], higher_is_better: bool) -> str | None:
    present = {k: v for k, v in values.items() if isinstance(v, (int, float))}
    if not present:
        return None
    return (max if higher_is_better else min)(present, key=lambda k: present[k])


def render(root: Path) -> str:
    study = read_json(root / "study_manifest.json")
    if study is None:
        raise SystemExit(f"Not a study root (no study_manifest.json): {root}")
    validation = read_json(root / "validation_report.json")
    search = read_json(root / "search" / "search_manifest.json")
    selected = read_json(root / "search" / "selected_architecture.json")

    summaries: dict[str, dict[str, Any]] = {}
    operating: dict[str, dict[str, Any]] = {}
    metrics: dict[str, dict[str, Any]] = {}
    for workflow in WORKFLOW_ORDER:
        directory = root / "workflows" / workflow
        payload = read_json(directory / "workflow_summary.json")
        if payload is not None:
            summaries[workflow] = payload
            operating[workflow] = read_json(directory / "selected_operating_point.json") or {}
            metrics[workflow] = read_json(directory / "event_metrics.json") or {}
    present = [workflow for workflow in WORKFLOW_ORDER if workflow in summaries]

    lines: list[str] = []
    add = lines.append
    study_id = study.get("study_id", "unknown")

    add(f"# Results: {study_id}")
    add("")
    add(
        "> Generated by `docs/build_results.py` from the study artifacts. "
        "Do not edit by hand; regenerate instead."
    )
    add("")

    add("## Study identity")
    add("")
    valid = (validation or {}).get("valid")
    errors = (validation or {}).get("errors") or []
    if validation is None:
        verdict = "not yet run"
    elif valid:
        verdict = "**valid**"
    else:
        verdict = f"**INVALID** ({len(errors)} errors)"
    lines.extend(
        table(
            ["Property", "Value"],
            [
                ["Study ID", f"`{study_id}`"],
                ["Artifact schema", str(study.get("schema_version"))],
                ["Status", str(study.get("status"))],
                ["`validate-study`", verdict],
                ["Data contract", short(study.get("data_contract_fingerprint"))],
                ["Study config", short(study.get("study_config_fingerprint"))],
                ["Source contract", short(study.get("source_contract_fingerprint"))],
                ["Preprocessing", short(study.get("preprocessing_fingerprint"))],
            ],
            numeric_from=99,
        )
    )
    if errors:
        add("Validation errors:")
        add("")
        for error in errors:
            add(f"- {error}")
        add("")

    if search is not None:
        add("## Architecture search")
        add("")
        pymoo = search.get("pymoo_result") or {}
        budget = search.get("execution_budget") or {}
        rows = [
            ["Execution mode", str(search.get("execution_mode", "fresh_search"))],
            ["Status", str(search.get("status"))],
            ["Generations completed", fmt(pymoo.get("completed_generations"))],
            ["Evaluations", fmt(pymoo.get("evaluations"))],
            ["Candidates evaluated", fmt(search.get("candidate_count"))],
            ["Valid candidates", fmt(search.get("valid_candidate_count"))],
            ["Pareto-front size", fmt(search.get("pareto_candidate_count"))],
            ["Stop reason", str(pymoo.get("stop_reason", "-"))],
            ["Generation budget", fmt(budget.get("max_generations"))],
            ["Per-job time budget", str(budget.get("max_time", "-"))],
        ]
        migration = search.get("migration")
        if migration:
            rows.append(["Migrated from", f"`{migration.get('donor_study_id')}`"])
        lines.extend(table(["Property", "Value"], rows, numeric_from=99))

    if selected is not None:
        architecture = selected.get("architecture") or {}
        add("### Selected architecture")
        add("")
        lines.extend(
            table(
                ["Property", "Value"],
                [
                    ["Label", f"`{architecture.get('label')}`"],
                    ["Recurrent cell", str(architecture.get("recurrent_cell"))],
                    ["Encoder hidden dims", str(architecture.get("encoder_hidden_dims"))],
                    ["Latent dim", str(architecture.get("latent_dim"))],
                    ["Decoder hidden dims", str(architecture.get("decoder_hidden_dims"))],
                    ["Activation", str(architecture.get("activation"))],
                    ["Sequence length", str(architecture.get("sequence_length"))],
                    ["Input dim", str(architecture.get("input_dim"))],
                ],
                numeric_from=99,
            )
        )
        objectives = selected.get("selected_objectives") or {}
        if objectives:
            add(
                "Winning objective values: reconstruction `"
                + fmt(objectives.get("obj_error"))
                + "`, PdM `"
                + fmt(objectives.get("obj_pdm"))
                + "`, alarm burden `"
                + fmt(objectives.get("obj_alarm_burden"))
                + "`."
            )
            add("")

    if not present:
        add("## Workflows")
        add("")
        add("No completed workflows in this study root yet.")
        add("")
        return "\n".join(lines) + "\n"

    add("## Event detection")
    add("")
    add(f"Evaluated over {len(present)} workflows on one shared anchor population.")
    add("")
    winners = {
        "recall": best({w: summaries[w].get("recall") for w in present}, True),
        "precision": best({w: summaries[w].get("precision") for w in present}, True),
        "f1": best({w: summaries[w].get("f1") for w in present}, True),
        "fp": best({w: summaries[w].get("fp") for w in present}, False),
    }
    rows = []
    for workflow in present:
        summary = summaries[workflow]

        def mark(key: str, value: str, current: str = workflow) -> str:
            return f"**{value}**" if winners.get(key) == current else value

        rows.append(
            [
                f"`{workflow}`",
                fmt(summary.get("tp"), 0),
                fmt(summary.get("fn"), 0),
                mark("fp", fmt(summary.get("fp"), 0)),
                mark("recall", fmt(summary.get("recall"))),
                mark("precision", fmt(summary.get("precision"))),
                mark("f1", fmt(summary.get("f1"))),
            ]
        )
    lines.extend(table(["Workflow", "TP", "FN", "FP", "Recall", "Precision", "F1"], rows))

    add("## Alarm burden")
    add("")
    burden = {
        "coverage_percent": best(
            {w: summaries[w].get("coverage_percent") for w in present}, False
        ),
        "far_per_day": best({w: summaries[w].get("far_per_day") for w in present}, False),
        "false_alarm_islands": best(
            {w: summaries[w].get("false_alarm_islands") for w in present}, False
        ),
        "nab_standard": best({w: summaries[w].get("nab_standard") for w in present}, True),
    }
    rows = []
    for workflow in present:
        summary = summaries[workflow]

        def markb(key: str, value: str, current: str = workflow) -> str:
            return f"**{value}**" if burden.get(key) == current else value

        rows.append(
            [
                f"`{workflow}`",
                markb("coverage_percent", fmt(summary.get("coverage_percent"), 2)),
                markb("far_per_day", fmt(summary.get("far_per_day"), 3)),
                fmt(summary.get("alarm_islands"), 0),
                markb("false_alarm_islands", fmt(summary.get("false_alarm_islands"), 0)),
                markb("nab_standard", fmt(summary.get("nab_standard"), 2)),
            ]
        )
    lines.extend(
        table(
            [
                "Workflow",
                "Coverage %",
                "FAR/day",
                "Alarm islands",
                "False-alarm islands",
                "NAB",
            ],
            rows,
        )
    )

    add("## Timeliness")
    add("")
    rows = []
    for workflow in present:
        summary = summaries[workflow]
        ttd = (metrics.get(workflow) or {}).get("ttd") or {}
        rows.append(
            [
                f"`{workflow}`",
                fmt(summary.get("ttd_minutes"), 2),
                fmt(ttd.get("median_ttd"), 2),
                fmt(ttd.get("detected_events"), 0),
                fmt(ttd.get("missed_events"), 0),
                fmt(summary.get("faa"), 4),
                fmt(summary.get("mtia_minutes"), 2),
            ]
        )
    lines.extend(
        table(
            [
                "Workflow",
                "Mean TTD (min)",
                "Median TTD",
                "Detected",
                "Missed",
                "First-alarm acc.",
                "MTIA (min)",
            ],
            rows,
        )
    )

    add("## Selected operating points")
    add("")
    reference = next((operating[w] for w in present if operating.get(w)), {})
    target_recall = reference.get("target_recall")
    target_coverage = reference.get("target_coverage")
    if target_recall is not None:
        add(
            f"Target region is `recall >= {target_recall}` and `coverage < {target_coverage}`. "
            "A workflow reports `feasible` when some threshold satisfies both, otherwise "
            "`fallback`: the threshold minimising distance to the target region."
        )
        add("")
    rows = []
    for workflow in present:
        point = operating.get(workflow, {})
        rows.append(
            [
                f"`{workflow}`",
                fmt(point.get("threshold"), 3),
                str(point.get("selection_mode", "-")),
                fmt(point.get("target_gap"), 4),
            ]
        )
    lines.extend(table(["Workflow", "theta", "Selection", "Target gap"], rows))

    modes = {operating.get(workflow, {}).get("selection_mode") for workflow in present}
    if modes == {"fallback"}:
        add(
            "> Every workflow selected a **fallback** operating point: no threshold in the "
            "sweep satisfied both targets. The comparison stays internally valid because one "
            "deterministic rule was applied to all workflows, but the reported points are "
            "closest misses rather than points meeting the specification. State this "
            "explicitly wherever these numbers are used."
        )
        add("")

    nianet = read_json(root / "workflows" / "nianetvae_per_maintenance" / "run_manifest.json")
    lineage = (nianet or {}).get("cycle_lineage") or []
    if lineage:
        add("## NiaNetVAE cycle lineage")
        add("")
        initial = sum(1 for c in lineage if c.get("model_status") == "trained_initial")
        tuned = sum(1 for c in lineage if c.get("model_status") == "fine_tuned")
        alias = sum(1 for c in lineage if str(c.get("model_status", "")).startswith("alias"))
        empty = sum(1 for c in lineage if int(c.get("prediction_count", 0) or 0) == 0)
        lines.extend(
            table(
                ["Property", "Count"],
                [
                    ["Maintenance cycles", str(len(lineage))],
                    ["Initial baseline training", str(initial)],
                    ["Fine-tuned", str(tuned)],
                    ["Alias (no trainable local window)", str(alias)],
                    ["Zero-anchor cycles (empty predictions)", str(empty)],
                ],
                numeric_from=99,
            )
        )
        if empty:
            add(
                f"{empty} cycles score zero evaluation anchors. They remain explicit in the "
                "lineage and produce zero-row prediction artifacts; they are never dropped and "
                "never change the shared evaluation population."
            )
            add("")

    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description="Render study artifacts as a wiki page.")
    parser.add_argument("study_root", help="Path to artifacts/<study_id>")
    parser.add_argument("-o", "--output", help="Write here instead of stdout")
    arguments = parser.parse_args()
    rendered = render(Path(arguments.study_root).expanduser().resolve())
    if arguments.output:
        Path(arguments.output).write_text(rendered, encoding="utf-8", newline="\n")
    else:
        sys.stdout.write(rendered)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
